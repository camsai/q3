#!/usr/bin/env python3
"""Keep each build-time add-on's engine-specific text inside that add-on.

An add-on lives under paths with an ``addons`` directory segment
(``src/addons/<name>/``, and the ``tests/`` and ``examples/`` trees that mirror
it). The public export leaves every such segment out, so text naming the
engine an add-on wraps has to stay there as well: a file anywhere else ships,
and carries the name with it. This check reads file contents and file paths and
reports every place that names one.

**Matching.** Text is cut into identifier-like tokens (runs of word characters),
and each token into sub-words at underscores and at camelCase and acronym
boundaries: ``FooBARReader`` becomes ``Foo``, ``BAR``, ``Reader``. A plural ``s``
or ``es`` after an acronym stays with it, so ``BARsReader`` is ``BARs`` and ``Reader``.
Digits stay with the letters before them, so ``Bar2`` is one sub-word, and it
also stands for ``Bar``. Every denylist entry has exactly one mode:

- ``sub-word``: case-insensitive; any sub-word equals the term, or the term
  with a plural ``s`` or ``es``, and so does the whole token. A possessive needs
  no rule of its own: the apostrophe ends the token, so ``Bar's`` holds ``Bar``.
- ``whole-word``: case-sensitive; a whole token equals the term. For a term
  that is also an ordinary word inside longer names, ``NUMBER_OF_TERM`` and
  ``term_list`` stay clean and only the bare token matches.
- ``phrase``: case-insensitive; two adjacent words equal the term's two words.
  Adjacent means consecutive sub-words, inside one identifier or across
  whitespace, a line break or a comment leader, but not across ``.,;:!?`` or a
  number.

Long base64 runs (embedded images, compressed diagrams) and hexadecimal digests
are masked before any of this, because a random run can spell anything.

**The denylist.** ``check_no_addon_leak_denylist.json`` beside this script holds
only salted SHA-256 digests and their modes, so no exported file spells out a
term. The terms are short, guessable words: hashing keeps them out of plain
text, and does not make them secret. Anyone can hash a guess and compare it.
Each add-on keeps its plain-text list in ``src/addons/<name>/leak_terms.txt``,
which never ships because of its ``addons`` segment, and ``--regenerate``
rebuilds the hashed file from every such list. A finding prints the path, the
line and the entry's id, never the term.

**Exempt.** Every path with an ``addons`` directory segment; ``schemas/esse/``,
vendored upstream text; the contents of binary files (their paths are still
checked); and every path the scanned root's ``.releaseignore`` excludes, when it
has one. ``ReleaseIgnoreRules`` reads that file.

    python scripts/repo/check_no_addon_leak.py FILE...           # what pre-commit runs
    python scripts/repo/check_no_addon_leak.py --all             # every tracked file
    python scripts/repo/check_no_addon_leak.py --root DIRECTORY  # all of a packed tree
    python scripts/repo/check_no_addon_leak.py --regenerate      # rebuild the denylist

``--report-only`` prints the findings and exits 0. ``--summary`` prints a count
per top-level directory in place of the findings themselves.
"""

import argparse
import bisect
import functools
import hashlib
import json
import os
import re
import secrets
import subprocess
import sys
from collections.abc import Iterator
from pathlib import Path
from typing import NamedTuple

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
#: The hashed denylist this check ships with.
DENYLIST_PATH = Path(__file__).resolve().with_name("check_no_addon_leak_denylist.json")
#: Each add-on's plain-text term list, relative to the repository root.
TERM_LIST_PATTERN = "src/addons/*/leak_terms.txt"
RELEASE_IGNORE = ".releaseignore"
#: The directory segment that every add-on path carries.
ADDON_SEGMENT = "addons"
#: Vendored upstream text. It is exported unchanged, so it is exempt rather than reworded.
#: A recorded decision: the engine names in the vendored ESSE schemas are accepted third-party data.
VENDORED_PREFIXES = ("schemas/esse/",)

SUB_WORD_MODE = "sub-word"
WHOLE_WORD_MODE = "whole-word"
PHRASE_MODE = "phrase"
MODES = (SUB_WORD_MODE, WHOLE_WORD_MODE, PHRASE_MODE)

#: How many leading hexadecimal digits of an entry's digest a finding prints.
ENTRY_IDENTIFIER_LENGTH = 12
DENYLIST_DESCRIPTION = (
    "Salted SHA-256 digests of the terms each add-on keeps out of every other path, and how "
    "each one matches. Generated by scripts/repo/check_no_addon_leak.py --regenerate from the "
    "add-ons' own term lists; do not edit by hand."
)

#: An identifier-like token: a run of word characters.
TOKEN = re.compile(r"\w+")
#: A token that can match: one with a letter in it. Numeric data is most of the
#: tokens of a dataset file, and none of them can, so they are never visited.
LETTERED_TOKEN = re.compile(r"(?<!\w)\w*[A-Za-z]\w*")
#: One sub-word of an underscore-free token: an acronym with a plural ``s`` or ``es``
#: (the ``BARs`` of ``BARsReader``, which would otherwise split as ``BA`` and ``Rs``), an
#: acronym running into a capitalized word (the ``BAR`` of ``BARReader``), a
#: capitalized or lower-case word, an acronym, or a bare number. Digits stay with
#: the letters before them.
SUB_WORD = re.compile(
    r"[A-Z]{2,}e?s(?![a-z])|[A-Z]+[0-9]*(?=[A-Z][a-z])|[A-Z]?[a-z]+[0-9]*|[A-Z]+[0-9]*|[0-9]+"
)
#: The plural endings a sub-word term also matches with.
PLURAL_SUFFIXES = ("s", "es")
#: What ends a phrase between two tokens: punctuation, or a word character, which
#: is a token without a letter (a number) standing between them.
PHRASE_BREAK = re.compile(r"[.,;:!?]|\w")
#: A candidate base64 run; `looks_encoded` decides whether it is data or words.
#: The lookbehind starts a match only where a run starts, so each run is read once.
BASE64_RUN = re.compile(r"(?<![A-Za-z0-9+/])[A-Za-z0-9+/]{40,}={0,2}")
#: A hexadecimal digest: 32 digits or more, not part of a longer word.
HEXADECIMAL_RUN = re.compile(r"(?<![0-9A-Za-z])[0-9A-Fa-f]{32,}(?![0-9A-Za-z])")
SMALL_LETTER_RUN = re.compile(r"[a-z]+")
#: In random base64 the runs of small letters average 1.65 letters; in the
#: tree's longest identifiers, never below 3.17 (measured 2026-10-19). The cut
#: sits low, because masking a real identifier would hide a finding.
ENCODED_MEAN_SMALL_LETTER_RUN = 2.5
#: A comment: ``#`` at the start of a line or after whitespace, to the end of the line.
COMMENT = re.compile(r"(?:^|\s)#.*$")


class ConfigurationError(Exception):
    """The check cannot run as asked: a missing or malformed denylist or term list."""


# ── .releaseignore ───────────────────────────────────────────────────────────


class ReleaseIgnoreRules(NamedTuple):
    """
    What a ``.releaseignore`` keeps out of the public export.

    The syntax is glob-free: ``name/`` is a directory segment of that name at any
    depth, ``a/b/`` is everything under that prefix of the root, any other entry
    is one exact file, and ``#`` starts a comment.
    """

    segments: frozenset[str]
    files: frozenset[str]
    prefixes: tuple[str, ...]

    def excludes(self, relative_path: str) -> bool:
        """Whether the export leaves out *relative_path* (POSIX, relative to the root)."""
        if relative_path in self.files:
            return True
        if any(relative_path.startswith(prefix) for prefix in self.prefixes):
            return True
        return any(directory in self.segments for directory in relative_path.split("/")[:-1])


def parse_release_ignore(text: str) -> ReleaseIgnoreRules:
    """The rules of one ``.releaseignore`` text."""
    segments: set[str] = set()
    files: set[str] = set()
    prefixes: list[str] = []
    for raw_line in text.splitlines():
        line = COMMENT.sub("", raw_line).strip()
        if not line:
            continue
        if line.endswith("/") and "/" not in line[:-1]:
            segments.add(line[:-1])
        elif line.endswith("/"):
            prefixes.append(line)
        else:
            files.add(line)
    return ReleaseIgnoreRules(frozenset(segments), frozenset(files), tuple(prefixes))


def read_release_ignore(root: Path) -> ReleaseIgnoreRules | None:
    """The rules of *root*'s ``.releaseignore``, or None when it has none (a packed tree)."""
    manifest = root / RELEASE_IGNORE
    if not manifest.is_file():
        return None
    return parse_release_ignore(manifest.read_text(encoding="utf-8"))


# ── Tokens ───────────────────────────────────────────────────────────────────


def sub_words(token: str) -> list[str]:
    """The sub-words of one token in order: split at underscores, then at case changes."""
    return [piece for part in token.split("_") for piece in SUB_WORD.findall(part)]


def sub_word_forms(piece: str) -> tuple[str, ...]:
    """
    The forms one sub-word is compared in: lower-cased, and without trailing digits.

    A bare number has none. No term is digits alone, so it can match nothing, and
    it separates the words on either side of it rather than joining them.
    """
    lowered = piece.lower()
    stem = lowered.rstrip("0123456789")
    if not stem:
        return ()
    return (lowered, stem) if stem != lowered else (lowered,)


def plural_stems(lowered: str) -> tuple[str, ...]:
    """
    What a lower-cased word would be without a plural ending, for sub-word terms.

    ``boxes`` gives ``boxe`` and ``box``: the word cannot say which ending it
    has, so both are tried. A stem must keep a letter, or it could match nothing.
    """
    return tuple(
        lowered[: -len(suffix)]
        for suffix in PLURAL_SUFFIXES
        if lowered.endswith(suffix) and re.search("[a-z]", lowered[: -len(suffix)])
    )


def looks_encoded(run: str) -> bool:
    """
    Whether a long run of base64 characters is encoded data rather than words.

    Encoded data mixes digits, capitals and small letters throughout, so its runs
    of small letters are short. An identifier, however it is capitalized, is
    made of words several letters long, even a long test name with digits in it.
    """
    body = run.rstrip("=")
    if not (re.search("[0-9]", body) and re.search("[A-Z]", body)):
        return False
    small_letter_runs = SMALL_LETTER_RUN.findall(body)
    if not small_letter_runs:
        return False
    letters = sum(len(small_letter_run) for small_letter_run in small_letter_runs)
    return letters < ENCODED_MEAN_SMALL_LETTER_RUN * len(small_letter_runs)


def mask_encoded_runs(text: str) -> str:
    """
    *text* with every encoded run overwritten, so that it matches nothing.

    Each run becomes the same number of full stops: offsets and line numbers
    hold, and no phrase runs across the gap.
    """
    spans = [match.span() for match in BASE64_RUN.finditer(text) if looks_encoded(match.group())]
    spans += [match.span() for match in HEXADECIMAL_RUN.finditer(text)]
    if not spans:
        return text
    pieces = []
    position = 0
    for start, end in sorted(spans):
        start = max(start, position)
        if start >= end:
            continue
        pieces += [text[position:start], "." * (end - start)]
        position = end
    pieces.append(text[position:])
    return "".join(pieces)


# ── The denylist ─────────────────────────────────────────────────────────────


def term_digest(salt: str, mode: str, normalized_term: str) -> str:
    """The salted SHA-256 that the denylist stores for one normalized term."""
    return hashlib.sha256(f"{salt}\n{mode}\n{normalized_term}".encode()).hexdigest()


def is_one_sub_word(word: str) -> bool:
    """Whether *word* is a single sub-word with a letter in it, so that it can match."""
    return sub_words(word) == [word] and bool(sub_word_forms(word))


def normalize_term(mode: str, term: str) -> str:
    """The form *term* is hashed in under *mode*; ValueError if it could never match."""
    if mode == SUB_WORD_MODE:
        if not is_one_sub_word(term):
            raise ValueError(
                "a sub-word term must be one sub-word with a letter in it: no underscore, "
                "case change or bare number"
            )
        return term.lower()
    if mode == WHOLE_WORD_MODE:
        if not TOKEN.fullmatch(term) or not re.match("[A-Za-z]", term):
            raise ValueError("a whole-word term must be one identifier-like token, led by a letter")
        return term
    if mode == PHRASE_MODE:
        words = term.split()
        if len(words) != 2 or not all(is_one_sub_word(word) for word in words):
            raise ValueError("a phrase must be exactly two words, each one sub-word")
        return " ".join(word.lower() for word in words)
    raise ValueError(f"unknown mode; expected one of {', '.join(MODES)}")


class DenylistEntry(NamedTuple):
    """One hashed term: its salted SHA-256 digest and the mode it matches in."""

    digest: str
    mode: str

    @property
    def identifier(self) -> str:
        """The short id a finding prints in place of the term."""
        return self.digest[:ENTRY_IDENTIFIER_LENGTH]


class Denylist(NamedTuple):
    """The shipped data: one salt, and the entries hashed with it."""

    salt: str
    entries: tuple[DenylistEntry, ...]


def read_denylist_document(path: Path) -> dict:
    """The parsed JSON of a denylist file."""
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ConfigurationError(f"cannot read the denylist {path}: {error}") from error
    if not isinstance(document, dict) or not isinstance(document.get("salt"), str):
        raise ConfigurationError(f"the denylist {path} has no salt")
    return document


def load_denylist(path: Path) -> Denylist:
    """The denylist at *path*, refused when it is malformed or empty."""
    document = read_denylist_document(path)
    entries = []
    for item in document.get("entries", []):
        try:
            entry = DenylistEntry(item["digest"], item["mode"])
        except (KeyError, TypeError) as error:
            raise ConfigurationError(f"the denylist {path} has a malformed entry") from error
        if entry.mode not in MODES or not re.fullmatch(r"[0-9a-f]{64}", entry.digest):
            raise ConfigurationError(f"the denylist {path} has a malformed entry")
        entries.append(entry)
    if not entries:
        # A denylist with no entries passes every tree, which reads as clean.
        raise ConfigurationError(f"the denylist {path} is empty, so nothing would be checked")
    return Denylist(document["salt"], tuple(entries))


def denylist_text(denylist: Denylist) -> str:
    """The denylist file's exact text, one key per line and a trailing newline."""
    document = {
        "description": DENYLIST_DESCRIPTION,
        "salt": denylist.salt,
        "entries": [{"digest": entry.digest, "mode": entry.mode} for entry in denylist.entries],
    }
    return json.dumps(document, indent=4) + "\n"


class TermListEntry(NamedTuple):
    """One line of an add-on's term list, normalized for hashing."""

    mode: str
    normalized_term: str


def read_term_list(path: Path) -> list[TermListEntry]:
    """
    The entries of one add-on's ``leak_terms.txt``: ``<mode> <term>`` per line.

    Errors name the file and line but never the term, like the findings.
    """
    entries = []
    for number, raw_line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = COMMENT.sub("", raw_line).strip()
        if not line:
            continue
        fields = line.split(maxsplit=1)
        if len(fields) != 2:
            raise ConfigurationError(f"{path}:{number}: expected '<mode> <term>'")
        try:
            entries.append(TermListEntry(fields[0], normalize_term(fields[0], fields[1])))
        except ValueError as error:
            raise ConfigurationError(f"{path}:{number}: {error}") from None
    return entries


def regenerated_denylist(root: Path, denylist_path: Path) -> Denylist:
    """
    The denylist rebuilt from every add-on term list under *root*.

    It keeps the salt of the existing file at *denylist_path*, so an unchanged
    term list regenerates the same bytes; only a first generation draws a new
    salt. Entries are deduplicated and sorted by digest, which says nothing about
    the order or the add-on they came from.
    """
    term_lists = sorted(root.glob(TERM_LIST_PATTERN))
    if not term_lists:
        raise ConfigurationError(
            f"no {TERM_LIST_PATTERN} under {root}: regenerating would empty the denylist"
        )
    unique_entries = {entry for path in term_lists for entry in read_term_list(path)}
    if not unique_entries:
        raise ConfigurationError("the add-on term lists hold no entries")
    if denylist_path.exists():
        salt = read_denylist_document(denylist_path)["salt"]
    else:
        salt = secrets.token_hex(16)
    entries = sorted(
        DenylistEntry(term_digest(salt, entry.mode, entry.normalized_term), entry.mode)
        for entry in unique_entries
    )
    return Denylist(salt, tuple(entries))


# ── Matching ─────────────────────────────────────────────────────────────────


class TokenAnalysis(NamedTuple):
    """What one token contributes to the matching, the same wherever it appears."""

    #: Whole-word, sub-word and phrase entries matched inside the token itself.
    entries: tuple[DenylistEntry, ...]
    #: The forms of its first and last sub-words, for phrases that span two tokens.
    first_forms: tuple[str, ...]
    last_forms: tuple[str, ...]


class TermMatcher:
    """Finds denylisted terms in a text while holding only their digests."""

    def __init__(self, denylist: Denylist) -> None:
        self._salt = denylist.salt
        self._entries = {(entry.mode, entry.digest): entry for entry in denylist.entries}
        # A token recurs thousands of times across a tree, and so does a pair of
        # neighbouring words: analyse and hash each distinct one once.
        self._entry = functools.lru_cache(maxsize=1 << 16)(self._find_entry)
        self._analysis = functools.lru_cache(maxsize=1 << 18)(self._analyse)
        self._joining_phrases = functools.lru_cache(maxsize=1 << 18)(self._phrases_between)

    def _find_entry(self, mode: str, normalized_term: str) -> DenylistEntry | None:
        return self._entries.get((mode, term_digest(self._salt, mode, normalized_term)))

    def _phrases_between(
        self, left: tuple[str, ...], right: tuple[str, ...]
    ) -> tuple[DenylistEntry, ...]:
        """The phrase entries that one word, in any of its forms, makes with the next."""
        found = (
            self._entry(PHRASE_MODE, f"{first} {second}") for first in left for second in right
        )
        return tuple(entry for entry in found if entry is not None)

    def _analyse(self, token: str) -> TokenAnalysis:
        forms = [sub_word_forms(piece) for piece in sub_words(token)]
        if not any(forms):
            # No sub-word with a letter (a letter outside ASCII, say): nothing can
            # match, and no phrase runs through it.
            return TokenAnalysis((), (), ())
        # Whole-word terms start with a letter, so a token that starts otherwise
        # (the 5E of 1.5E+01, which is distinct for every value) needs no hash.
        entries = [self._entry(WHOLE_WORD_MODE, token) if token[0].isalpha() else None]
        entries += [self._entry(SUB_WORD_MODE, form) for piece in forms for form in piece]
        # A plural reaches a sub-word term too, as one sub-word or as the whole
        # token, whichever way its letters split.
        singulars = {stem for piece in forms if piece for stem in plural_stems(piece[0])}
        singulars.update(plural_stems(token.lower()))
        entries += [self._entry(SUB_WORD_MODE, stem) for stem in sorted(singulars)]
        for left, right in zip(forms, forms[1:]):
            entries += self._phrases_between(left, right)
        return TokenAnalysis(
            tuple(entry for entry in entries if entry is not None), forms[0], forms[-1]
        )

    def matches(self, text: str) -> Iterator[tuple[int, DenylistEntry]]:
        """(character offset, entry) for every place *text* contains a denylisted term."""
        masked = mask_encoded_runs(text)
        analyse, joining_phrases = self._analysis, self._joining_phrases
        previous_forms: tuple[str, ...] = ()
        previous_offset = previous_end = 0
        for token_match in LETTERED_TOKEN.finditer(masked):
            analysis = analyse(token_match.group())
            offset = token_match.start()
            for entry in analysis.entries:
                yield offset, entry
            if previous_forms and analysis.first_forms:
                joining = joining_phrases(previous_forms, analysis.first_forms)
                if joining and not PHRASE_BREAK.search(masked, previous_end, offset):
                    # Reported where the phrase starts, on the earlier word's line.
                    for entry in joining:
                        yield previous_offset, entry
            previous_forms, previous_offset = analysis.last_forms, offset
            previous_end = token_match.end()


# ── Scanning ─────────────────────────────────────────────────────────────────


class Finding(NamedTuple):
    """One denylisted term outside an add-on: where it is, and which entry (never the term)."""

    path: str
    #: 0 for a match in the path itself.
    line: int
    entry: DenylistEntry

    def render(self) -> str:
        """``path:line: ...`` for the text, ``path: ...`` for the path itself."""
        label = f"add-on term, entry {self.entry.identifier} ({self.entry.mode})"
        if self.line:
            return f"{self.path}:{self.line}: {label}"
        return f"{self.path}: {label} in the path"


def looks_binary(data: bytes) -> bool:
    """A NUL byte early on, the same test the export packer uses."""
    return b"\0" in data[:8192]


def is_exempt(relative_path: str, release_ignore: ReleaseIgnoreRules | None = None) -> bool:
    """Whether *relative_path* is outside the check: an add-on, vendored, or never exported."""
    if ADDON_SEGMENT in relative_path.split("/")[:-1]:
        return True
    # The trailing slash makes the vendored root itself, a submodule entry, match too.
    if any(f"{relative_path}/".startswith(prefix) for prefix in VENDORED_PREFIXES):
        return True
    return release_ignore is not None and release_ignore.excludes(relative_path)


def scan_text(relative_path: str, text: str, matcher: TermMatcher) -> list[Finding]:
    """The findings in one file's text, one per line and entry."""
    newline_offsets = [match.start() for match in re.finditer("\n", text)]
    found = {
        (bisect.bisect_right(newline_offsets, offset) + 1, entry)
        for offset, entry in matcher.matches(text)
    }
    return [Finding(relative_path, line, entry) for line, entry in sorted(found)]


def scan_file(root: Path, relative_path: str, matcher: TermMatcher) -> list[Finding]:
    """The findings in a path itself, then in its text unless the file is binary."""
    in_path = sorted({entry for _, entry in matcher.matches(relative_path)})
    findings = [Finding(relative_path, 0, entry) for entry in in_path]
    location = root / relative_path
    if location.is_symlink():
        # What the repository stores for a link; following it could leave the tree.
        data = os.readlink(location).encode()
    elif location.is_file():
        data = location.read_bytes()
    else:
        # A submodule's directory, or a tracked file deleted in the working tree.
        return findings
    if looks_binary(data):
        return findings
    return findings + scan_text(relative_path, data.decode("utf-8", errors="replace"), matcher)


def scan(
    root: Path,
    relative_paths: list[str],
    matcher: TermMatcher,
    release_ignore: ReleaseIgnoreRules | None,
) -> list[Finding]:
    """The findings in every path of *relative_paths* that the check covers."""
    findings = []
    for relative_path in relative_paths:
        if not is_exempt(relative_path, release_ignore):
            findings += scan_file(root, relative_path, matcher)
    return findings


def tracked_files(root: Path) -> list[str]:
    """Every path git tracks under *root*."""
    listing = subprocess.run(
        ["git", "-C", str(root), "ls-files", "-z"],
        capture_output=True,
        text=True,
    )
    if listing.returncode != 0:
        raise ConfigurationError(f"--all needs a git repository at {root}; --root alone walks it")
    return [entry for entry in listing.stdout.split("\0") if entry]


def every_file(root: Path) -> list[str]:
    """Every file under *root*, for a tree that is not a repository, such as a packed export."""
    found = []
    for directory, subdirectories, files in os.walk(root):
        subdirectories[:] = sorted(name for name in subdirectories if name != ".git")
        for name in files:
            if name != ".git":
                found.append((Path(directory) / name).relative_to(root).as_posix())
    return sorted(found)


def relative_to_root(argument: str, root: Path) -> str:
    """A file argument as a POSIX path relative to *root*; a relative one already is."""
    path = Path(argument)
    if not path.is_absolute():
        return path.as_posix()
    # Resolve the directory, not the file: a link named on the command line is
    # checked as the link.
    located = Path(os.path.realpath(path.parent)) / path.name
    try:
        return located.relative_to(root).as_posix()
    except ValueError:
        raise ConfigurationError(f"{argument} is not under {root}") from None


def summary_table(findings: list[Finding]) -> str:
    """A Markdown table of findings and files per top-level directory."""
    per_directory: dict[str, tuple[int, set[str]]] = {}
    for finding in findings:
        head, separator, _ = finding.path.partition("/")
        directory = f"`{head}/`" if separator else "(top level)"
        count, paths = per_directory.get(directory, (0, set()))
        per_directory[directory] = (count + 1, paths | {finding.path})
    rows = ["| Top-level directory | Findings | Files |", "| --- | ---: | ---: |"]
    for directory, (count, paths) in sorted(per_directory.items()):
        rows.append(f"| {directory} | {count} | {len(paths)} |")
    total_files = len({finding.path for finding in findings})
    rows.append(f"| Total | {len(findings)} | {total_files} |")
    return "\n".join(rows)


GUIDANCE = (
    "Each add-on's engine-specific text belongs under its addons/ paths, which the public "
    "export leaves out. Move the file there or reword the line. The terms behind the entry "
    "ids are in each add-on's leak_terms.txt, in the raw repository."
)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument(
        "paths", nargs="*", help="files to check, relative to the root (what pre-commit passes)"
    )
    parser.add_argument("--all", action="store_true", help="check every file git tracks")
    parser.add_argument(
        "--root",
        type=Path,
        default=None,
        help="the tree to check, such as a packed export (default: this repository); "
        "given alone, every file under it is checked",
    )
    parser.add_argument("--report-only", action="store_true", help="print the findings, but exit 0")
    parser.add_argument(
        "--summary",
        action="store_true",
        help="print a count per top-level directory instead of each finding",
    )
    parser.add_argument(
        "--regenerate",
        action="store_true",
        help=f"rebuild the denylist from every {TERM_LIST_PATTERN} under the root",
    )
    parser.add_argument(
        "--denylist",
        type=Path,
        default=DENYLIST_PATH,
        help="the hashed denylist (default: the one beside this script)",
    )
    arguments = parser.parse_args(argv)
    if arguments.all and arguments.paths:
        parser.error("--all checks every tracked file; do not also name files")
    root = (arguments.root or REPOSITORY_ROOT).resolve()

    try:
        if arguments.regenerate:
            denylist = regenerated_denylist(root, arguments.denylist)
            arguments.denylist.write_text(denylist_text(denylist), encoding="utf-8")
            print(f"wrote {len(denylist.entries)} entries to {arguments.denylist}")
            return 0
        if arguments.all:
            relative_paths = tracked_files(root)
        elif arguments.paths:
            relative_paths = [relative_to_root(argument, root) for argument in arguments.paths]
        elif arguments.root is not None:
            relative_paths = every_file(root)
        else:
            parser.error("name files to check, or pass --all or --root")
        matcher = TermMatcher(load_denylist(arguments.denylist))
        findings = scan(root, relative_paths, matcher, read_release_ignore(root))
    except ConfigurationError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if arguments.summary:
        print(summary_table(findings))
    else:
        for finding in findings:
            print(finding.render())
    if not findings:
        return 0
    files = len({finding.path for finding in findings})
    print(f"\n{len(findings)} add-on term(s) in {files} file(s) outside addons/", file=sys.stderr)
    if arguments.report_only:
        print("report-only: not failing", file=sys.stderr)
        return 0
    print(GUIDANCE, file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
