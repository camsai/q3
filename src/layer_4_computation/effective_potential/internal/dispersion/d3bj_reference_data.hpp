/// sqrt(0.5 * <r^4>/<r^2> * sqrt(Z)) atomic values, indexed by atomic number (1-based).
inline Real r2r4_by_atomic_number(int atomic_number) {
    switch (atomic_number) {
        case 6:
            return 3.10492822; // C
        case 14:
            return 4.88284902; // Si
        case 24:
            return 5.54643096; // Cr
        case 26:
            return 5.58415602; // Fe
        case 28:
            return 5.28497229; // Ni
        case 29:
            return 5.22592821; // Cu
        default:
            return 0.0;
    }
}

/// D3 covalent radii (Pyykko-Atsumi, metals scaled -10%), indexed by atomic number.
inline Real rcov_by_atomic_number(int atomic_number) {
    switch (atomic_number) {
        case 6:
            return 1.88972601; // C
        case 14:
            return 2.62041997; // Si
        case 24:
            return 2.77159820; // Cr
        case 26:
            return 2.62041997; // Fe
        case 28:
            return 2.49443835; // Ni
        case 29:
            return 2.54483100; // Cu
        default:
            return 0.0;
    }
}

