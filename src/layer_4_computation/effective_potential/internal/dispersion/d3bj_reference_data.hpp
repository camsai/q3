/**
 * DFT-D3(BJ) reference data for elements currently supported by Q3.
 *
 * Physical constants (coordination-number-dependent C6 dispersion
 * coefficients, covalent radii, <r^4>/<r^2> ratios), not source code:
 * extracted from the tables published in
 *
 *   S. Grimme, J. Antony, S. Ehrlich, H. Krieg,
 *   J. Chem. Phys. 132, 154104 (2010)
 *   S. Grimme, S. Ehrlich, L. Goerigk,
 *   J. Comput. Chem. 32, 1456 (2011) (Becke-Johnson damping)
 *
 * and cross-checked against Quantum ESPRESSO's dft-d3 module (a
 * GPL-licensed repackaging of Grimme's reference code) purely to
 * confirm which published values it uses -- this file is an original,
 * independent re-implementation covering only the elements Q3
 * currently supports (Si, Cu, Fe, Ni, Cr, C), not a derivative of
 * that GPL source.
 *
 * C6ReferencePoint entries are the (CN_i, CN_j, C6) grid used by the
 * Gaussian-weighted coordination-number interpolation (Grimme 2010,
 * eq. 8); r2r4/rcov are indexed directly by atomic number. Entries
 * are pre-symmetrized (both (Z_i,Z_j) and (Z_j,Z_i) orderings present)
 * so callers need only match (Z_i, Z_j) directly, never the swap.
 */

